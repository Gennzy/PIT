ALTER DEFAULT PRIVILEGES IN SCHEMA pit REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated;

CREATE FUNCTION pit.consume_rate_limit(p_key text) RETURNS integer
LANGUAGE sql SET search_path = '' AS $$
 INSERT INTO pit.rate_limits(key,window_start,hits) VALUES(p_key,now(),1)
 ON CONFLICT(key) DO UPDATE SET
 window_start=CASE WHEN pit.rate_limits.window_start<now()-interval '10 minutes' THEN now() ELSE pit.rate_limits.window_start END,
 hits=CASE WHEN pit.rate_limits.window_start<now()-interval '10 minutes' THEN 1 ELSE pit.rate_limits.hits+1 END
 RETURNING hits;
$$;
REVOKE ALL ON FUNCTION pit.consume_rate_limit(text) FROM PUBLIC, anon, authenticated;

