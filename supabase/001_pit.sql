-- PIT v6. Dedicated private schema; existing public/auth tables are untouched.
CREATE SCHEMA IF NOT EXISTS pit;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;
SET LOCAL search_path = pit, extensions, pg_catalog;

CREATE TABLE pit.tenants (
 id text PRIMARY KEY, slug text UNIQUE NOT NULL CHECK (slug ~ '^[a-z0-9][a-z0-9-]{2,49}$'),
 owner_key text NOT NULL, config jsonb NOT NULL, revision integer NOT NULL DEFAULT 1 CHECK(revision>0)
);
CREATE TABLE pit.users (
 id text PRIMARY KEY, tenant text NOT NULL REFERENCES pit.tenants(id), email text NOT NULL,
 name text NOT NULL, phone text NOT NULL DEFAULT '', role text NOT NULL CHECK(role IN ('owner','master','client')),
 hash text NOT NULL, UNIQUE(tenant,email), UNIQUE(tenant,id)
);
CREATE TABLE pit.sessions (
 token text PRIMARY KEY CHECK(length(token)=64), user_id text NOT NULL REFERENCES pit.users(id), expires bigint NOT NULL
);
CREATE TABLE pit.vehicles (
 id text PRIMARY KEY, tenant text NOT NULL REFERENCES pit.tenants(id), user_id text NOT NULL,
 data jsonb NOT NULL, UNIQUE(tenant,id), FOREIGN KEY(tenant,user_id) REFERENCES pit.users(tenant,id)
);
CREATE TABLE pit.bookings (
 id text PRIMARY KEY, tenant text NOT NULL REFERENCES pit.tenants(id), user_id text NOT NULL,
 vehicle text NOT NULL, date text NOT NULL CHECK(date ~ '^\d{4}-\d{2}-\d{2}$'),
 start integer NOT NULL CHECK(start>=0 AND start<1440), duration integer NOT NULL CHECK(duration>0),
 post integer NOT NULL CHECK(post BETWEEN 1 AND 16), status text NOT NULL CHECK(status IN ('booked','working','completed','cancelled','waitlist')),
 data jsonb NOT NULL, UNIQUE(tenant,id), CHECK(start+duration<=1440),
 FOREIGN KEY(tenant,user_id) REFERENCES pit.users(tenant,id),
 FOREIGN KEY(tenant,vehicle) REFERENCES pit.vehicles(tenant,id),
 EXCLUDE USING gist (tenant WITH =, date WITH =, post WITH =, int4range(start,start+duration,'[)') WITH &&)
 WHERE (status IN ('booked','working'))
);
CREATE UNIQUE INDEX pit_one_working_per_post ON pit.bookings(tenant,post) WHERE status='working';
CREATE TABLE pit.notifications (
 id text PRIMARY KEY, tenant text NOT NULL REFERENCES pit.tenants(id), user_id text NOT NULL,
 message text NOT NULL, created text NOT NULL, is_read integer NOT NULL DEFAULT 0 CHECK(is_read IN(0,1)),
 FOREIGN KEY(tenant,user_id) REFERENCES pit.users(tenant,id)
);
CREATE TABLE pit.storage (
 tenant text NOT NULL REFERENCES pit.tenants(id), cell text NOT NULL CHECK(cell ~ '^[ABC]-(0[1-9]|1[0-9]|20)$'),
 vehicle text NOT NULL, data jsonb NOT NULL, PRIMARY KEY(tenant,cell), UNIQUE(tenant,vehicle),
 FOREIGN KEY(tenant,vehicle) REFERENCES pit.vehicles(tenant,id)
);
CREATE TABLE pit.shares (
 token text PRIMARY KEY CHECK(length(token)=48), tenant text NOT NULL REFERENCES pit.tenants(id),
 vehicle text NOT NULL, expires bigint NOT NULL, FOREIGN KEY(tenant,vehicle) REFERENCES pit.vehicles(tenant,id)
);
CREATE TABLE pit.audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant text NOT NULL REFERENCES pit.tenants(id),
 user_id text NOT NULL, action text NOT NULL, target text NOT NULL, created text NOT NULL,
 FOREIGN KEY(tenant,user_id) REFERENCES pit.users(tenant,id)
);
CREATE TABLE pit.photos (
 id text PRIMARY KEY, tenant text NOT NULL, booking text NOT NULL, object_path text UNIQUE NOT NULL,
 mime text NOT NULL CHECK(mime IN('image/jpeg','image/png','image/webp')),
 FOREIGN KEY(tenant,booking) REFERENCES pit.bookings(tenant,id)
);
CREATE TABLE pit.rate_limits (key text PRIMARY KEY, window_start timestamptz NOT NULL, hits integer NOT NULL);
CREATE INDEX pit_booking_schedule ON pit.bookings(tenant,date,status,start);
CREATE INDEX pit_vehicle_owner ON pit.vehicles(tenant,user_id);
CREATE INDEX pit_notes_owner ON pit.notifications(tenant,user_id,created DESC);
CREATE INDEX pit_session_expiry ON pit.sessions(expires);
CREATE INDEX pit_share_expiry ON pit.shares(expires);

